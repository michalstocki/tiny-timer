import board as B


def layout_json():
    d = B.to_json()
    d["derived"] = dict(
        board_center=[B.D["cx"], B.D["cy"]],
        oled_module=dict(rect=B.body_rect("OLED"), pcb_thickness_assumed=1.2,
                         total_thickness_above_board=B.P["oled_thickness"] + B.P["oled_standoff"],
                         glass_rect=[B.D["oled_pin_x"] + B.P["glass_to_pin"],
                                     B.D["oled_cy"] - B.P["glass_h"] / 2,
                                     B.D["oled_pin_x"] + B.P["glass_to_pin"] + B.P["glass_w"],
                                     B.D["oled_cy"] + B.P["glass_h"] / 2]),
        buttons={ref: dict(centre=[B.PARTS[ref]["x"], B.PARTS[ref]["y"]], body=12.0,
                           plunger_square=B.P["btn_plunger"], cap_diameter=B.P["btn_cap_d"],
                           top_above_board=B.P["btn_height"],
                           label={"S3": "minus", "S1": "run", "S2": "plus"}[ref])
                 for ref in ("S3", "S1", "S2") if ref in B.PARTS},
        back_envelope_height=B.P["bottom_height"],
        front_free_zone_above_board="everything on the front except the OLED module and the buttons must stay below 2.0 mm (solder joints of the back parts)")
    if B.VARIANT == "klin":
        d["variant"] = "klin"
        d["derived"]["front_free_zone_above_board"] = "everything on the front except the OLED module must stay below 2.0 mm (solder joints of the back parts)"
        d["button_board"] = dict(
            note="separate board with the 3 buttons, wired to the KEY pads of the main board",
            width=48.0, depth=16.0, thickness=B.P["thickness"], corner_radius=2.0,
            buttons=[dict(label="minus", ref="S3", x=8.0, y=8.0), dict(label="run", ref="S1", x=24.0, y=8.0),
                     dict(label="plus", ref="S2", x=40.0, y=8.0)],
            mounting_holes=[dict(x=16.0, y=8.0, diameter=2.2), dict(x=32.0, y=8.0, diameter=2.2)],
            wires=dict(KEY1="GND (S1, S2 common)", KEY2="PB3 (S1 run)", KEY3="PB4 (S2 plus, S3 minus)",
                       KEY4="S3 low side (to R6 on the main board)"))
    return d


def scad_params(d):
    L = ["// Generated by tools/pcb (iteration 1). Millimetres, front view, origin = lower-left of the board.",
         "board_w = %.2f; board_h = %.2f; board_t = %.2f; board_corner_r = %.2f;" % (
             d["board"]["width"], d["board"]["height"], d["board"]["thickness"], d["board"]["corner_radius"]),
         "mount_holes = [%s]; // [x, y]" % ", ".join("[%.2f, %.2f]" % (h["x"], h["y"]) for h in d["mounting_holes"]),
         "mount_hole_d = %.2f; mount_keepout_r = %.2f;" % (B.P["mount_d"], B.P["mount_keepout_r"])]
    o = d["derived"]["oled_module"]
    g = o["glass_rect"]
    L += ["oled_module = [%.2f, %.2f, %.2f, %.2f]; // x0, y0, x1, y1 (ESTIMATED module outline)" % tuple(o["rect"]),
          "oled_glass = [%.2f, %.2f, %.2f, %.2f];" % tuple(g),
          "oled_total_height = %.2f; // above the board's top surface (assumes 2.5 mm header standoff)" % o["total_thickness_above_board"]]
    for ref, b in d["derived"]["buttons"].items():
        L.append("button_%s = [%.2f, %.2f]; // centre; body 12x12, plunger 3.8 sq, cap d 7.1, top at %.1f mm" % (
            b["label"], b["centre"][0], b["centre"][1], b["top_above_board"]))
    if B.VARIANT == "base":
        L.append("button_top_height = %.2f; button_body = 12; button_plunger = 3.8; button_cap_d = 7.1;" % B.P["btn_height"])
    else:
        L.append("// buttons are on a separate board (48 x 16 mm), see pcb-layout.json: button_board")
    L.append("back_envelope_height = %.2f;" % B.P["bottom_height"])
    L.append("// back-side parts: [name, x0, y0, x1, y1, height]")
    items = []
    for ref, p in d["parts"].items():
        if p["side"] == "bottom" and p["body"]:
            b = p["body"]
            items.append('["%s", %.2f, %.2f, %.2f, %.2f, %.2f]' % (ref, b[0], b[1], b[2], b[3], p["height_above_board"]))
    L.append("back_parts = [\n  " + ",\n  ".join(items) + "\n];")
    return "\n".join(L) + "\n"


def side_svg():
    """Side elevation (looking along +x ... shows heights stack at the section through the middle button)."""
    S = 20.0
    M = 40
    W, H = B.P["W"], B.P["H"]
    t = B.P["thickness"]
    top_h = max(B.P["btn_height"] if B.VARIANT == "base" else 0.0, B.P["oled_thickness"] + B.P["oled_standoff"])
    bot_h = B.P["bottom_height"]
    wpx = int(W * S + 2 * M)
    hpx = int((top_h + t + bot_h) * S + 2 * M + 60)
    y0 = M + top_h * S               # top surface of the board
    p = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" width="%d" height="%d" font-family="Helvetica, Arial, sans-serif">' % (wpx, hpx, wpx, hpx),
         '<rect width="100%" height="100%" fill="#fff"/>',
         '<text x="%d" y="22" font-size="12" font-weight="bold">Rzut z boku: wysokości elementów (wszystkie elementy rzutowane na płaszczyznę x–z; x w prawo)</text>' % M]

    def rect(x0, z0, x1, z1, fill, label=None, stroke="#222"):
        # z measured up from the top surface of the board (negative = back side)
        p.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="%s" stroke="%s" stroke-width="1"/>' % (
            M + x0 * S, y0 - z1 * S, (x1 - x0) * S, (z1 - z0) * S, fill, stroke))
        if label:
            p.append('<text x="%.1f" y="%.1f" font-size="9" text-anchor="middle" fill="#111">%s</text>' % (
                M + (x0 + x1) / 2 * S, y0 - (z0 + z1) / 2 * S + 3, label))
    rect(0, -t, W, 0, "#2f6b3a")
    # OLED module: PCB 1.2 + glass, standing on a 2.5 mm header
    o = B.body_rect("OLED")
    so = B.P["oled_standoff"]
    rect(o[0], so, o[2], so + 1.2, "#16335f", "OLED")
    gx0 = B.D["oled_pin_x"] + B.P["glass_to_pin"]
    rect(gx0, so + 1.2, gx0 + B.P["glass_w"], so + B.P["oled_thickness"], "#05070b")
    rect(B.D["oled_pin_x"] - 1.3, 0, B.D["oled_pin_x"] + 1.3, so, "#555")
    for ref in [r for r in ("S3", "S1", "S2") if r in B.PARTS]:
        q = B.PARTS[ref]
        rect(q["x"] - 6, 0, q["x"] + 6, 4.3, "#3a3a40", ref)
        rect(q["x"] - B.P["btn_cap_d"] / 2, 4.3, q["x"] + B.P["btn_cap_d"] / 2, 5.5, "#202024")
        rect(q["x"] - 1.9, 5.5, q["x"] + 1.9, B.P["btn_height"], "#555")
    for ref in B.REFS_BOTTOM:
        pr = B.PARTS[ref]
        b = B.body_rect(ref)
        if b is None:
            continue
        h = B.FP[pr["fp"]]["height"]
        if ref == "U1":
            rect(b[0], -t - 4.5, b[2], -t, "#2b2b30", "gniazdo")
            rect(b[0] + 1.2, -t - 8.5, b[2] - 1.2, -t - 4.5, "#111", "ATtiny")
        else:
            rect(b[0], -t - h, b[2], -t, "#e8d3a6", ref)
    # dimension: envelope
    p.append('<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" stroke="#b00" stroke-dasharray="4 3"/>' % (M, y0 + (t + bot_h) * S, M + W * S, y0 + (t + bot_h) * S))
    p.append('<text x="%d" y="%.1f" font-size="10" fill="#b00">obwiednia tyłu: %.1f mm pod płytką</text>' % (M + 4, y0 + (t + bot_h) * S + 12, bot_h))
    if B.VARIANT == "base":
        p.append('<line x1="%d" y1="%.1f" x2="%d" y2="%.1f" stroke="#080" stroke-dasharray="4 3"/>' % (M, y0 - B.P["btn_height"] * S, M + W * S, y0 - B.P["btn_height"] * S))
        p.append('<text x="%d" y="%.1f" font-size="10" fill="#080">góra trzpienia przycisku: %.1f mm nad płytką</text>' % (M + 4, y0 - B.P["btn_height"] * S - 4, B.P["btn_height"]))
    p.append("</svg>")
    return "\n".join(p)


