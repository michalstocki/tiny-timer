#!/usr/bin/env bash
# Builds every firmware variant and collects hex files + the avr-size report in dist/.
set -euo pipefail
cd "$(dirname "$0")/../firmware"
DIST=../dist
rm -rf "$DIST"; mkdir -p "$DIST/attiny13a"
REPORT="$DIST/avr-size.txt"
{
  echo "avr-size report (generated by tools/make_dist.sh on $(date -u +%Y-%m-%d))"
  echo "Toolchain: $(make -s -n all 2>/dev/null | head -1 | awk '{print $1}')"
  echo
} > "$REPORT"

build() {  # dir mcu-label make-args...
  local dir=$1 label=$2; shift 2
  mkdir -p "$DIST/$dir"
  make clean >/dev/null
  make "$@" >/dev/null
  local out=build
  [ "${1:-}" = planb ] && out="build-$label"
  echo "## $dir ($label)" >> "$REPORT"
  for p in timer test_tone test_display test_buttons calib; do
    cp "$out/$p.hex" "$DIST/$dir/$p.hex"
  done
  make -s size $( [ "${1:-}" = planb ] && echo "OUT=$out MCU=$label F_CPU=8000000UL" ) 2>&1 \
    | sed -e 's/^/    /' >> "$REPORT"
  echo >> "$REPORT"
}

build attiny13a attiny13a all
make heat FREQ=2000 >/dev/null && cp build/test_heat.hex "$DIST/attiny13a/test_heat_2000Hz.hex"
for m in attiny25 attiny45 attiny85; do
  build "planb-$m" "$m" planb MCU_B=$m
done
make clean >/dev/null
ls -R "$DIST" | head -60
